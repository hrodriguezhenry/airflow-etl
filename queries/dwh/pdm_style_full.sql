	pst.buckle_2,
	pst.replacement_buckle,
	
	CONVERT(INT, pst.quantity_barrettes)  + 
	
	CASE
		WHEN pst.floating_barrette = 'Y' THEN 1
		ELSE 0 
	END AS quantity_barrettes,
	
	pst.hanger,
	pst.feather_edge_roller,
	pst.size_1,
	pst.size_2,
	pst.size_3,
