	pst.blurred_edges,
	pst.punch_perforation,
	pst.prints_quantity,
	pst.point_armhole,
	CONVERT(INT, pst.prelaminated) AS prelaminated,
	CONVERT(INT, pst.couplings) AS couplings,
	pst.dutton_style_type,
	sl.last_planning_date
FROM "process".pdm_style_third AS pst
LEFT JOIN (
	SELECT wp.style_id,
		MAX(CONVERT(date, wp.planning_date)) AS last_planning_date
	FROM source_fast_react.weekly_planning AS wp
	GROUP BY wp.style_id
) AS sl
ON pst.style_id = sl.style_id