	pst.color,
	pst.class,
	pst.customer_style,
	pst.top_layer_width,
	pst.lining_layer_width,
	pst.filler_layer_width_1,
	pst.filler_layer_width_2,
	pst.filler_layer_width_3,
	pst.top_layer_code,
	pst.lining_layer_code,
	pst.filler_layer_code_1,
	pst.filler_layer_code_2,
	pst.filler_layer_code_3,
	pst.top_glue,
	pst.bottom_glue,
	pst.glue_layers,
	pst.glue_layers_2,
	pst.ornamental_glue,
	pst.sets_glue,
	pst.super_wonder_glue,
	pst.edge_trimming_glued,
	pst.roughing_glued,
