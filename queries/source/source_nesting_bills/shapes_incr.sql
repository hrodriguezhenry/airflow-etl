SELECT s.ShapeId AS shape_id,
	s.ShapeSize AS shape_size,
	s.Component AS component,
	s."Set" AS "set",
	s.Code AS code,
	s.DieHeight AS die_height,
	s.LibraryId AS library_id,
	s.UserFlags AS user_flags,
	s.BaseAngle AS base_angle,
	s.DieProcessParameterSetId AS die_process_parameter_set_id,
	s.IsDieprocessed AS is_die_processed,
	s.NestingParameterSetId AS nesting_parameter_set_id,
	s.Status AS status,
	s.Priority AS priority,
	s.Xerr AS xerr,
	s.Yerr AS yerr,
	s.ShapeType AS shape_type,
	s.Class AS class,
	s."Group" AS "group",
	s.Area AS area,
	s.DeclaredArea AS declared_area,
	s.Perimeter AS perimeter,
	s.Season AS season,
	s.LastUpdated AS last_updated,
	s.StandardCutDuration AS standard_cut_duration
FROM Shapes AS s