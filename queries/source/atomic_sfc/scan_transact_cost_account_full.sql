SELECT sstca.id,
    sstca."day",
    sstca."year",
    sstca.week,
    sstca.days_work,
    sstca.cod_employee,
    sstca."name",
    sstca.scan_transact_id,
    sstca.sfc_scan_qr_id,
    sstca.rmi_ticket,
    sstca.standard_time,
    sstca.quantity,
    sstca.scan_transact_date,
    sstca.cust_ord_hdr_number,
    sstca.style_id,
    sstca.color_id,
    sstca.color_description,
    sstca.stage_id,
    sstca.stage_name,
    sstca.line_id,
    sstca.line_name,
    sstca.operation_id,
    sstca.operation_name,
    sstca.cost_center,
    sstca.cost_center_description,
    sstca.position,
    sstca.time_qr,
    sstca.time_lunch_daily,
    sstca.time_lunch_distribution,
    sstca.time_left,
    sstca.time_left_distribution,
    sstca.total_time_expected,
    sstca.cost_costco,
    sstca.distributed_pending_hour,
    sstca.distributed_pending_hour_area,
    sstca.created_at,
    sstca.updated_at
FROM SFC_Scan_Transact_Cost_Account AS sstca
WHERE sstca."year" = YEAR(DATEADD(MONTH, -1 + DATEDIFF(MONTH, 0, GETDATE()), 0))
AND MONTH(sstca."day") = MONTH(DATEADD(MONTH, -1 + DATEDIFF(MONTH, 0, GETDATE()), 0))