SELECT sdc.id,
	sdc."day",
	sdc.week,
	sdc."year",
	sdc.cod_employee,
	sdc.type_distribution_id,
	sdc.position,
	sdc.cost_center,
	sdc.cost_center_description,
	sdc.concept,
	sdc.dollar_change,
	sdc.pay,
	sdc.no_production_cost,
	sdc.no_production_area_cost,
	sdc.cost_distributed,
	sdc.distributable,
	sdc.cost_total,
	sdc.distributed_status,
	sdc.pending_hour,
	sdc.distributed_pending_hour,
	sdc.distributed_pending_hour_area,
	sdc.created_at,
	sdc.created_by,
	sdc.updated_at
FROM SFC_Daily_Cost AS sdc
WHERE sdc.deleted_at IS NULL