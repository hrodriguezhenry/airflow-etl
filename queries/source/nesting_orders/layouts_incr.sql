SELECT l.LayoutId AS layout_id,
    l.SessionId AS session_id,
    l.LayoutNumber AS layout_number,
    l.Name AS name,
    l.MaterialId AS material_id,
    l.Layers AS layers,
    l.TimesToCut AS times_to_cut,
    l.TimesCut AS times_cut,
    l.YBetween AS y_between,
    l.LayersMode AS layers_mode,
    l.Length AS length,
    l.Width AS width,
    l.Status AS status,
    l.IsPostBuilt AS is_post_built,
    l.AcquiredMatArea AS acquired_mat_area,
    l.DeclaredMatArea AS declared_mat_area,
    l.Yield AS yield,
    l.InstancesArea AS instances_area,
    l.NumInstances AS num_instances,
    l.DeclaredInstancesArea AS declared_instances_area,
    l.NestDuration AS nest_duration,
    l.NestDate AS nest_date,
    l.CutDuration AS cut_duration,
    l.LatestCutDate AS latest_cut_date,
    l.LastUpdated AS last_updated,
    l.AcquiredRestArea AS acquired_rest_area,
    l.DeclaredRestArea AS declared_rest_area
FROM Layouts AS l
WHERE CONVERT(date, l.NestDate) >= CONVERT(date, GETDATE() -7)