SELECT w."Day" AS "day",
	w.Day_Name_sp AS day_name,
	w.Week AS week,
	w."Month" AS "month",
	w.Month_Name AS month_name,
	w."Year" AS "year",
	w.Real_Month AS real_month,
	w.Real_Month_Name AS real_month_name,
	w.Real_Year AS real_year,
	w.First_Day_of_Week AS first_day_of_week,
	w.Last_Day_of_Week AS last_day_of_week,
	w.Laboral_Hours AS laboral_hours,
	w.Laboral_Day AS laboral_day,
	w.Entry_Time AS entry_time,
	w.Departure_Time AS departure_time,
	w.Apply_MOD AS apply_mod
FROM Weeks AS w