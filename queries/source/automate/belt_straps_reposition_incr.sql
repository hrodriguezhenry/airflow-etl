SELECT arf.ID AS id,
    arf.Boleta AS ticket_number,
    arf.Estatus AS 'status',
    arf.GerApp AS manager_approval_id,
    arf.Solicitante AS requester_id,
    arf.L_Produccion AS production_line,
    arf.Orden AS cust_order,
    arf.Estilo AS style_id,
    arf.Color AS color,
    arf.CantRepo AS reported_quantity,
    arf.AnchoFaja AS belt_width,
    arf.RepProcede AS report_accepted,
    arf.FalMaterial AS missing_material,
    arf.PerFajas AS belt_loss,
    arf.Holgura AS tolerance,
    arf.Urgencia AS urgency,
    arf.CodRevisor AS reviewer_code,
    arf.RespRepo AS report_responsible,
    arf.DetRepo AS report_details,
    arf.CodEntrega AS delivery_code,
    arf.F_Inicio AS start_date,
    arf.FA_TareaActual AS current_task_date,
    arf.TareaActual AS current_task,
    arf.F_Final AS end_date,
    arf.RefRec AS references_received,
    arf.Auditoria AS audit,
    arf.Observaciones AS observations,
    arf.View AS 'view',
    arf.Process AS 'process',
    arf.EstadoFlujo AS flow_status,
    arf.created_at,
    arf.updated_at
FROM AUTOMATE_REPO_FAJAS AS arf
WHERE arf.deleted_at IS NULL
AND arf.updated_at >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)
