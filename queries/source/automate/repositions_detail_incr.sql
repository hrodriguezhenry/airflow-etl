SELECT dr.ID_FLUJO AS flow_id,
    dr.ETAPA AS stage,
    dr.BOLETA AS ticket_number,
    dr.LINEA AS line_code,
    dr.LINEA_DESC AS line_description,
    dr.LINEA_PRODUCCION AS production_line,
    dr.ORDEN AS cust_ord,
    dr.CLIENTE AS customer_id,
    dr.ESTILO AS style_id,
    dr.ESTILO_CLIENTE AS customer_style,
    dr.COLOR AS color,
    dr.COLABORADOR AS cod_employee,
    dr.NOMBRE_COLABORADOR AS employee_name,
    dr.REPOSICIONES AS repositions_quantity,
    dr.RAZON_REPO AS reposition_reason,
    dr.FECHA AS 'date',
    dr.REPO_PROCEDE AS reposition_approved,
    dr.CATEGORIA AS category,
    dr.ORIGEN AS origin,
    dr.FECHA_MODIFICACION AS modification_date,
    dr.IdRazon AS reason_id,
    dr.FECHA_CREACION AS created_at,
    dr.FECHA_ACTUALIZACION AS updated_at
FROM DETALLE_REPOSICIONES AS dr
WHERE dr.FECHA_ACTUALIZACION >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)
