SELECT b.StlNumber AS stl_number,
    b.ClrNumber AS clr_number,
    b.SzDimDetNumber AS sz_dim_det_number,
    b.BOMAmount AS bom_amount,
    b.BOMArea AS bom_area,
    b.BOMAreaInches AS bom_area_inches,
    b.BOMWidth AS bom_width,
    b.BOMLength AS bom_length,
    b.MatCode AS mat_code,
    b.BOMOrder AS bom_order,
    b.StDetUnique AS st_det_unique,
    b.BOMDesc AS bom_desc,
    b.BOMOutOfRange AS bom_out_of_range,
    b.BOMActive AS bom_active
FROM BOM AS b