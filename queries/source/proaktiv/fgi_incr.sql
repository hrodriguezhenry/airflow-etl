SELECT CRC32(COALESCE(f.FGITicketNumber, 'N/A')) AS unique_id,
    f.FGITicketNumber AS fgi_ticket_number,
    f.FGITicketPrefix AS fgi_ticket_prefix,
    f.LocCode AS loc_code,
    f.StlNumber AS stl_number,
    f.ClrNumber AS clr_number,
    f.SzDimDetNumber AS sz_dim_det_number,
    f.CustOrdHdrNumber AS cust_ord_hdr_number,
    IF(f.FGIProductionDate = '0000-00-00', NULL, f.FGIProductionDate) AS fgi_production_date,
    IF(f.FGIShipDate = '0000-00-00', NULL, f.FGIShipDate) AS fgi_ship_date,
    f.FGIQty AS fgi_qty,
    f.FGIStatus AS fgi_status,
    f.FGISemiPT AS fgi_semi_pt,
    f.FGIPartial AS fgi_partial,
    f.FGIOrigTicketNumber AS fgi_orig_ticket_number,
    f.LineNumber AS line_number,
    f.UsrNumber AS usr_number,
    f.FGIOrdExp AS fgi_ord_exp,
    f.UpdateDate AS update_date
FROM FGI AS f
WHERE DATE(f.UpdateDate) >= DATE_SUB(CURDATE(), INTERVAL 2 DAY)