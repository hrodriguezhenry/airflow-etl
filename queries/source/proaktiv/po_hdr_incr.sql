SELECT ph.POHdrNumber AS po_hdr_number,
    ph.POHdrCorr AS po_hdr_corr,
    ph.VendNumber AS vend_number,
    ph.UsrNumber AS usr_number,
    IF(ph.POHdrEntryDate = '0000-00-00', NULL, ph.POHdrEntryDate) AS po_hdr_entry_date,
    IF(ph.POHdrFirstETA = '0000-00-00', NULL, ph.POHdrFirstETA) AS po_hdr_first_eta,
    IF(ph.POHdrETA = '0000-00-00', NULL, ph.POHdrETA) AS po_hdr_eta,
    IF(ph.POHdrFirstExVendorFactory = '0000-00-00', NULL, ph.POHdrFirstExVendorFactory) AS po_hdr_first_ex_vendor_factory,
    IF(ph.POHdrExVendorFactory = '0000-00-00', NULL, ph.POHdrExVendorFactory) AS po_hdr_ex_vendor_factory,
    ph.POHdrShipment AS po_hdr_shipment,
    ph.POHdrInvoice AS po_hdr_invoice,
    ph.ImpCodHdr AS imp_cod_hdr,
    ph.POHdrStatus AS po_hdr_status,
    ph.ViaCode AS via_code,
    ph.POTypeCode AS po_type_code,
    ph.POHdrManualId AS po_hdr_manual_id,
    ph.POHdrAuthCom AS po_hdr_auth_com,
    ph.POHdrReasonManualPO AS po_hdr_reason_manual_po,
    ph.POHdrFechaConfirmacion AS po_hdr_confirmation_date,
    ph.POHdrDateETAConfirmed AS po_hdr_date_eta_confirmed,
    ph.UpdateDate AS update_date,
    IF(ph.PODateSent = '0000-00-00', NULL, ph.PODateSent) AS po_date_sent
FROM POHdr AS ph
WHERE DATE(ph.UpdateDate) >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)
OR DATE(ph.POHdrEntryDate) >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)