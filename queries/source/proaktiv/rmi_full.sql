SELECT r.RMITicketNumber AS rmi_ticket_number,
    r.RMITicketPrefix AS rmi_ticket_prefix,
    r.LocCode AS loc_code,
    r.MatCode AS mat_code,
    r.VendNumber AS vend_number,
    r.RMIReceptionCut AS rmi_reception_cut,
    r.RMIIssuingCut AS rmi_issuing_cut,
    r.POHdrNumber AS po_hdr_number,
    IF(r.RMIReceptionDate = '0000-00-00 00:00:00', NULL, r.RMIReceptionDate) AS rmi_reception_date,
    r.RMIIssuingDate AS rmi_issuing_date,
    r.RMIQty AS rmi_qty,
    r.RMIStatus AS rmi_status,
    r.RMIQualityCode AS quality_code,
    r.RMIDestino AS rmi_destination,
    r.UsrNumber AS usr_number,
    r.RMILeatherFormat AS rmi_leather_format,
    r.RMILastTicketScanDate AS rmi_last_ticket_scan_date,
    r.UpdateDate AS update_date
FROM RMI AS r
