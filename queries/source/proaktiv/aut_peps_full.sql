SELECT ap.idAutorizacion AS id_authorization,
    ap.CutNumber AS cut_number,
    ap.MatCode AS mat_code,
    ap.VendNumber AS vend_number,
    ap.autEstado AS status,
    ap.autReason AS reason,
    ap.autUserSolicitante AS requesting_user,
    ap.autUserSolAutoriza AS requesting_user_authorizing,
    ap.autUserAutoriza AS authorizing_user,
    ap.autUserRechaza AS rejecting_user,
    ap.autDateAutorizado AS authorization_date,
    ap.autDateRechazado AS rejection_date,
    ap.autDatePendiente AS pending_date,
    ap.UpdateDate AS update_date
FROM autPeps AS ap