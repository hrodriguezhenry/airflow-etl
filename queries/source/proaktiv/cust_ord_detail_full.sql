SELECT cod.CustOrdHdrNumber AS cust_ord_hdr_number,
    cod.StlNumber AS stl_number,
    cod.ClrNumber AS clr_number,
    cod.SzDimDetNumber AS sz_dim_det_number,
    cod.CustOrdDetQty AS cust_ord_det_qty,
    cod.CustOrdDetQtyOrig AS cust_ord_det_qty_orig,
    cod.CustOrdDetQtyMin AS cust_ord_det_qty_min,
    cod.CustOrdDetPrice AS cust_ord_det_price,
    cod.CustOrdDetPurchasePrice AS cust_ord_det_purchase_price,
    cod.CustQtyTotal AS cust_qty_total,
    cod.CustOrdStyleCore AS cust_ord_style_core,
    cod.CustTipePackig AS cust_tipe_packig,
    cod.UnityPrepack AS unity_prepack,
    cod.CustOrdStyle AS cust_ord_style,
    cod.CustOrdColor AS cust_ord_color,
    cod.CustOrdSize AS cust_ord_size,
    cod.CustOrdBoxSize AS cust_ord_box_size,
    cod.CustOrdPrepackCaja AS cust_ord_prepack_box,
    cod.UpdateDate AS update_date
FROM CustOrdDetail AS cod
WHERE cod.CustOrdHdrNumber != ''