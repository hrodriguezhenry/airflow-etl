SELECT m.MaterialId AS material_id,
    m.OriginalMaterialId AS original_material_id,
    m.SessionId AS session_id,
    m.Sequence AS sequence,
    m.BatchId AS batch_id,
    m.Quantity AS quantity,
    m.BookedQuantity AS booked_quantity,
    m.NestedQuantity AS nested_quantity,
    m.CutQuantity AS cut_quantity,
    m.MatType AS mat_type,
    m.Length AS length,
    m.Width AS width,
    m.Thickness AS thickness,
    m.UserFlags AS user_flags,
    m.MaterialFile AS material_file,
    m.AcqDate AS acq_date,
    m.AcqDuration AS acq_duration,
    m.DeclaredMatArea AS declared_mat_area,
    m.AcquiredMatArea AS acquired_mat_area,
    m.Layers AS layers,
    m.Gap AS gap,
    m.MaterialCodeId AS material_code_id,
    m.LastUpdated AS last_updated,
    m.SupplierId AS supplier_id,
    m.CostPerSqMt AS cost_per_sq_mt,
    m.SourceLayoutId AS source_layout_id
FROM Materials AS m