SELECT ls.LayShapeId AS lay_shape_id,
    ls.SessionId AS session_id,
    ls.ShapeId AS shape_id,
    ls.IsFromExplosion AS is_from_explosion,
    ls.Sequence AS sequence,
    ls.NormalTodo AS normal_all,
    ls.NormalDone AS normal_done,
    ls.MirroredTodo AS mirrored_everything,
    ls.MirroredDone AS mirrored_done,
    ls.NestingParameterSetId AS nesting_parameter_set_id,
    ls.Status AS status,
    ls.OrderId AS order_id,
    ls.IsFiller AS is_filler,
    ls.NormalRejected AS normal_rejected,
    ls.MirroredRejected AS mirrored_rejected
FROM LayShapes AS ls