SELECT pee.EPDO_CODIGO AS cod_employee,
	pee.EPDO_NOMBRE_COMPLETO AS name,
	msc.ID AS permission_type_id,
	msc.DESCRIPCION AS permission_type,
	sc.OBSERVACION AS observation,
	sc.FECHA_INICIO AS start_date,
	sc.FECHA_FIN AS end_date
FROM SUSPENSION_CLINICA AS sc
INNER JOIN MOTIVO_SUSPENSION_CLINICA AS msc
ON sc.CODIGO_MOTIVO = msc.ID
INNER JOIN PAZ_EPDO_EMPLEADO AS pee
ON sc.COMPANIA = pee.EPDO_CODCIA
AND sc.CODIGO_EMPLEADO =  pee.EPDO_CODIGO
INNER JOIN PAZ_USR_USUARIOS AS puu
ON puu.USR_USUARIO = sc.USUARIO
WHERE pee.EPDO_ESTADO = 'A'