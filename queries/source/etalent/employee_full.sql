SELECT pee.EPDO_CODCIA AS cod_company,
    pee.EPDO_CODIGO AS cod_employee,
    pee.EPDO_PRIMER_APE AS first_last_name,
    pee.EPDO_SEGUNDO_APE AS second_last_name,
    pee.EPDO_PRIMER_NOM AS first_name,
    pee.EPDO_SEGUNDO_NOM AS second_name,
    pee.EPDO_DIRECCION AS direction,
    pee.EPDO_PROFESION AS profession,
    pee.EPDO_ESTADO AS status,
    pee.EPDO_FECHA_INGRESO AS entry_date,
    pee.EPDO_FECHA_RETIRO AS retirement_date,
    pee.EPDO_CODMRT AS cod_reason_liquidation,
    pee.EPDO_CODTPL AS cod_type_payroll,
    pee.EPDO_CODPLZ AS cod_position,
    pee.EPDO_CELULAR AS phone_number,
    pee.EPDO_NOMBRE_COMPLETO AS full_name,
    pee.EPDO_SEXO AS gender,
    pee.EPDO_EDAD AS age,
    pee.EPDO_FECHA_NAC AS birthdate,
    pee.EPDO_ESTADO_CIVIL AS marital_status,
    pee.EDPO_EMPL_NUMERO_HIJOS AS number_children
FROM PAZ_EPDO_EMPLEADO AS pee