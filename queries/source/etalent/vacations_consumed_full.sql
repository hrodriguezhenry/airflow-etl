SELECT CASE 
		WHEN ppp.VAR2 IS NULL THEN 'S/C' 
		WHEN ppp.VAR2 = '' THEN 'S/C' 
		ELSE CONVERT(VARCHAR, ppp.VAR2) 
	END AS payroll,
	
	pee.EPDO_CODIGO AS cod_employee,
	pee.EPDO_NOMBRE_COMPLETO AS name,
	pddv.DVCON_PERIODO AS period,
	CONVERT(date, pddv.DVCON_DESDE) AS from_date,
	CONVERT(date, pddv.DVCON_HASTA) AS to_date,
	pddv.DVCON_DIAS AS days
	
FROM PAZ_DVCON_DET_VACACION AS pddv
JOIN PAZ_EPDO_EMPLEADO AS pee
ON pddv.DVCON_CODCIA = pee.EPDO_CODCIA
AND pddv.DVCON_CODEMP =  pee.EPDO_CODIGO

INNER JOIN PAZ_PLA_PLAZA AS ppp
ON pee.EPDO_CODCIA = ppp.PLA_CODCIA
AND pee.EPDO_CODPLZ = ppp.PLA_CODIGO

WHERE EPDO_CODTPL <> 1