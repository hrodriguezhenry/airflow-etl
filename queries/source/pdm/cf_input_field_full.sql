SELECT ci.nID AS id,
    ci.strName AS name,
    ci.nType AS `type`,
    ci.strStandardValue AS standard_value,
    ci.bReadOnly AS read_only,
    ci.bAudit AS audit,
    ci.strEnglishName AS english_name,
    ci.nAction AS `action`,
    ci.strDisplayName AS display_name,
    ci.palabra AS word,
    ci.orden AS `order`,
    ci.constante AS constant,
    ci.constanteF AS f_constant,
    ci.letra AS lyrics,
    ci.MatClsInvType AS mat_cls_inv_type,
    ci.constante_estilo AS style_constant,
    ci.padre AS father,
    ci.orden_edicion AS edition_order
FROM cf_inputfield AS ci
