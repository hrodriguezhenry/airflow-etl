SELECT ac.id,
    IF(ac.fecha = '0000-00-00', NULL, ac.fecha) AS date,
    ac.codigo AS code,
    ac.descripcion AS description,
    ac.factura AS invoice,
    ac.poliza AS policy,
    ac.po AS purchase_order,
    ac.paletas AS pallets,
    ac.pieles AS leathers,
    ac.embarque AS shipment,
    ac.recepcion AS reception,
    ac.medicion AS measurement,
    ac.diferencia AS difference,
    IF(ac.ingreso = '0000-00-00', NULL, ac.ingreso) AS entry,
    ac.proveedor AS supplier,
    ac.parcial AS partial,
    ac.pendiente_validar AS pending_validation,
    ac.shade_band AS shade_band,
    ac.estilo AS style,
    ac.swatch AS swatch,
    ac.prepro AS preproduction,
    ac.orden_completa AS complete_order,
    ac.produccion AS production,
    ac.estado AS status,
    ac.idsrechazos AS rejection_ids,
    ac.TamMuestreo AS sampling_size,
    ac.CantRecha AS rejected_qty,
    ac.CantRechaMane AS handled_rejected_qty,
    ac.estadoCliente AS customer_status
FROM amp_cabeceras AS ac